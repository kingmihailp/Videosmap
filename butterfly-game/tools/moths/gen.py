"""tools/moths/data/*.json -> src/moths_data.js (const MOTH_DATA) + tools/i18n/moths_en.json (Russian -> English texts of the rows). Checks that all names are unique across the game."""
import json, os, glob, re, sys
D = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(D, '..', '..')
ORDER = ['russia', 'alps', 'med', 'amazon', 'borneo', 'kenya', 'prairie', 'japan', 'bog', 'papua', 'vietnam', 'chihuahua']
sys.path.insert(0, D); import check
out = {}; en = {}; seen = {}; bad = 0
src = open(os.path.join(ROOT, 'src', 'species_more.js'), encoding='utf-8').read() + open(os.path.join(ROOT, 'src', 'data.js'), encoding='utf-8').read() + open(os.path.join(ROOT, 'src', 'species_ocean.js'), encoding='utf-8').read()
for b in ORDER:
    p = os.path.join(D, 'data', b + '.json')
    if not os.path.exists(p): print('missing', b); bad += 1; continue
    pr = check.check(p)
    if pr: print(b, 'PROBLEMS', pr[:5]); bad += 1
    rows = json.load(open(p, encoding='utf-8')); out[b] = rows
    for r in rows:
        if r['la'] in seen: print('DUPLICATE', r['la'], b, seen[r['la']]); bad += 1
        seen[r['la']] = b
        if "'" + r['la'] + "'" in src: print('already a butterfly', r['la']); bad += 1
        for k in ('hab', 'range', 'host', 'fact'): en[r[k]] = r[k + '_en']
        en[r['fam']] = en.get(r['fam'], '')          # family names are translated by hand (fixes.json)
rus = {}
for b, rows in out.items():
    for r in rows:
        if r['ru'] in rus and rus[r['ru']] != r['la']: print('same Russian name for two species', r['ru'], rus[r['ru']], r['la']); bad += 1
        rus[r['ru']] = r['la']
js = '// generated by tools/moths/gen.py from tools/moths/data/*.json - do not edit by hand\nconst MOTH_DATA = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(os.path.join(ROOT, 'src', 'moths_data.js'), 'w', encoding='utf-8').write(js)
json.dump(en, open(os.path.join(ROOT, 'tools', 'i18n', 'moths_en.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
print('species', sum(len(v) for v in out.values()), 'biomes', len(out), 'families', sorted({r['fam'] for v in out.values() for r in v}), 'PROBLEMS' if bad else 'OK')
sys.exit(1 if bad else 0)
