"""Merges tools/i18n/chunks/en_*.json (+ auto.json: pairs found in the data) into src/lang_en.js (const LANG_EN). Reports problems."""
import json, glob, os, re, sys
D = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(D, '..', '..')
ALLOWED = set(chr(c) for c in range(32, 127)) | set('—–·…×→←↑↓♥✓•°«»№’“”±≈½©★▪✕›\n')
CY = re.compile('[А-Яа-яЁё]')
keys = json.load(open(os.path.join(D, 'keys.json'), encoding='utf-8'))
out = {}; bad = []
for f in sorted(glob.glob(os.path.join(D, 'chunks', 'en_*.json'))):
    out.update(json.load(open(f, encoding='utf-8')))
# manual fixes (applied last)
fix = os.path.join(D, 'fixes.json')
if os.path.exists(fix): out.update(json.load(open(fix, encoding='utf-8')))
out.update(json.load(open(os.path.join(D, 'auto.json'), encoding='utf-8')))
miss = [k for k in keys if k not in out]
for k, v in out.items():
    lead = len(k) - len(k.lstrip()); trail = len(k) - len(k.rstrip())
    if not v.strip(): bad.append(('empty', k)); continue
    if CY.search(v): bad.append(('cyrillic left', k, v))
    if set(v) - ALLOWED: bad.append(('chars', k, ''.join(sorted(set(v) - ALLOWED))))
    if (k[:lead] != v[:lead]) or (trail and k[len(k) - trail:] != v[len(v) - trail:]) or (not trail and v != v.rstrip()): bad.append(('whitespace', k, v))
for b in bad[:60]: print(b)
print('keys', len(keys), 'translated', len(out), 'missing', len(miss), 'problems', len(bad))
if miss: print(miss[:10])
open(os.path.join(ROOT, 'src', 'lang_en.js'), 'w', encoding='utf-8').write('// generated by tools/i18n/merge.py from tools/i18n/chunks/en_*.json - do not edit by hand (use tools/i18n/fixes.json)\nconst LANG_EN = ' + json.dumps(out, ensure_ascii=False, indent=0, separators=(',', ':')).replace('\n', '\n') + ';\n')
sys.exit(1 if miss else 0)
